const _configTemplate =
    r'''// Generated public runtime settings. API origins are not secrets.
// Never put credentials, private keys, or tokens in this file or Dart defines.
class AppConfig {
  const AppConfig({
    required this.name,
    required this.displayName,
    required this.apiBaseUrl,
    required this.allowLocalHttp,
    required this.logMetadata,
    this.linkHost,
    this.linkPaths = const [],
  });

  final String name;
  final String displayName;
  final String apiBaseUrl;
  final bool allowLocalHttp;
  final bool logMetadata;
  final String? linkHost;
  final List<String> linkPaths;

  bool allowsLink(Uri uri) {
    if (linkHost == null || !linkPaths.any(uri.path.startsWith)) return false;
    if (!uri.hasAuthority) return !uri.hasScheme;
    return uri.scheme == 'https' && uri.host.toLowerCase() == linkHost!.toLowerCase() &&
        uri.userInfo.isEmpty && (!uri.hasPort || uri.port == 443);
  }

  void validate() {
    final uri = Uri.tryParse(apiBaseUrl);
    if (uri == null || !uri.hasAuthority || uri.host.isEmpty ||
        uri.userInfo.isNotEmpty || uri.hasQuery || uri.hasFragment) {
      throw StateError('Invalid public API base URL.');
    }
    final host = uri.host.toLowerCase();
    final localHost = host == 'localhost' || host == '::1' ||
        host.startsWith('127.') || host.startsWith('10.') ||
        host.startsWith('192.168.') || host.endsWith('.local') ||
        RegExp(r'^172\.(1[6-9]|2[0-9]|3[01])\.').hasMatch(host);
    if (uri.scheme != 'https' &&
        !(name == 'dev' && allowLocalHttp && localHost && uri.scheme == 'http')) {
      throw StateError('HTTPS is required except explicit local dev HTTP.');
    }
  }
}

