const _metadataTemplate =
    r'''import 'package:antsf_flutter_starter/antsf_flutter_starter.dart';

typedef MetadataLogSink = void Function(String message);

/// Intentionally excludes paths, queries, userinfo, headers, bodies, errors,
/// and redirect targets. Do not replace this with LogInterceptor.
class MetadataInterceptor extends Interceptor {
  MetadataInterceptor({required this.enabled, required this.log});

  final bool enabled;
  final MetadataLogSink log;

  void _record(RequestOptions request, int? status) {
    if (!enabled) return;
    final method = RegExp(r'^[A-Z]+$').hasMatch(request.method)
        ? request.method : 'OTHER';
    final uri = request.uri;
    final origin = (uri.scheme == 'https' || uri.scheme == 'http') && uri.host.isNotEmpty
        ? uri.origin : 'invalid-origin';
    log('HTTP $method $origin ${status ?? 'network-error'}');
  }

  @override
  void onResponse(Response<dynamic> response, ResponseInterceptorHandler handler) {
    _record(response.requestOptions, response.statusCode);
    handler.next(response);
  }

  @override
  void onError(DioException err, ErrorInterceptorHandler handler) {
    _record(err.requestOptions, err.response?.statusCode);
    handler.next(err);
  }
}
